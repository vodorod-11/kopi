import CryptoKit
import Foundation

/// Pasteboard type identifiers Kopi cares about (UTIs, as NSPasteboard reports them).
public enum PasteboardType {
    public static let string = "public.utf8-plain-text"
    public static let utf16Text = "public.utf16-external-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let gif = "com.compuserve.gif"
    public static let pdf = "com.adobe.pdf"

    public static let imageTypes = [png, jpeg, heic, gif, tiff]
    public static let richTextTypes: Set<String> = [rtf, rtfd, html]
    public static let textTypes: Set<String> = [string, utf16Text]

    /// Markers that apps put next to secrets or throw-away data (see nspasteboard.org).
    /// A copy that carries any of them is never recorded.
    public static let ignoredMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
}

/// One representation (type + bytes) of a pasteboard item.
public struct Representation: Equatable, Sendable {
    public var type: String
    public var data: Data

    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

/// One pasteboard item. A copy can hold several items (for example several files from Finder).
public struct ClipItem: Equatable, Sendable {
    public var representations: [Representation]

    public init(_ representations: [Representation]) {
        self.representations = representations
    }

    public var types: [String] { representations.map(\.type) }

    public func data(for type: String) -> Data? {
        representations.first { $0.type == type }?.data
    }
}

/// Everything that was on the pasteboard for one copy, in the order the source app wrote it.
public struct ClipContent: Equatable, Sendable {
    public var items: [ClipItem]

    public init(items: [ClipItem]) {
        self.items = items
    }

    public init(text: String) {
        items = [ClipItem([Representation(type: PasteboardType.string, data: Data(text.utf8))])]
    }

    public var byteSize: Int {
        items.reduce(0) { total, item in total + item.representations.reduce(0) { $0 + $1.data.count } }
    }

    public var allTypes: Set<String> {
        Set(items.flatMap(\.types))
    }

    /// The first representation of the first type in `types` that any item has.
    public func firstData(forAnyOf types: [String]) -> Representation? {
        for type in types {
            for item in items {
                if let data = item.data(for: type) {
                    return Representation(type: type, data: data)
                }
            }
        }
        return nil
    }

    public var fileURLs: [URL] {
        items.compactMap { item in
            item.data(for: PasteboardType.fileURL).flatMap { URL(dataRepresentation: $0, relativeTo: nil) }
        }
    }

    public var kind: ClipKind {
        let types = allTypes
        if types.contains(PasteboardType.fileURL) { return .files }
        let hasRichText = !types.isDisjoint(with: PasteboardType.richTextTypes)
        if !types.isDisjoint(with: PasteboardType.textTypes) {
            return hasRichText ? .richText : .text
        }
        if !types.isDisjoint(with: PasteboardType.imageTypes) || types.contains(PasteboardType.pdf) {
            return .image
        }
        if hasRichText { return .richText }
        if types.contains(PasteboardType.url) { return .text }
        return .other
    }

    /// Plain text that can be read without AppKit: file paths, plain text or a bare URL.
    /// Rich-text-only copies need the app layer to convert RTF or HTML.
    public var basicPlainText: String? {
        let urls = fileURLs
        if !urls.isEmpty {
            return urls.map { $0.isFileURL ? $0.path : $0.absoluteString }.joined(separator: "\n")
        }
        let texts = items.compactMap { item -> String? in
            if let data = item.data(for: PasteboardType.string) {
                return String(data: data, encoding: .utf8)
            }
            if let data = item.data(for: PasteboardType.utf16Text) {
                return String(data: data, encoding: .utf16)
            }
            if let data = item.data(for: PasteboardType.url) {
                return String(data: data, encoding: .utf8)
            }
            return nil
        }
        return texts.isEmpty ? nil : texts.joined(separator: "\n")
    }

    /// Identity used to spot a repeated copy. Based on what the user sees (files, text or the
    /// image), not on every representation: apps add volatile extras such as source URLs.
    public func contentHash(plainText: String?) -> String {
        var hasher = SHA256()
        let urls = fileURLs
        if !urls.isEmpty {
            hasher.update(data: Data("files\u{0}".utf8))
            for url in urls {
                hasher.update(data: Data(url.absoluteString.utf8))
                hasher.update(data: Data([0]))
            }
        } else if let text = plainText ?? basicPlainText, !text.isEmpty {
            hasher.update(data: Data("text\u{0}".utf8))
            hasher.update(data: Data(text.utf8))
        } else if let image = firstData(forAnyOf: PasteboardType.imageTypes + [PasteboardType.pdf]) {
            hasher.update(data: Data("image\u{0}".utf8))
            hasher.update(data: image.data)
        } else {
            hasher.update(data: Data("raw\u{0}".utf8))
            for item in items {
                for representation in item.representations {
                    hasher.update(data: Data(representation.type.utf8))
                    hasher.update(data: Data([0]))
                    hasher.update(data: representation.data)
                }
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

public enum ClipKind: Int, Sendable, CaseIterable {
    case text = 0
    case richText = 1
    case image = 2
    case files = 3
    case other = 4

    public var label: String {
        switch self {
        case .text: return "Text"
        case .richText: return "Rich text"
        case .image: return "Image"
        case .files: return "Files"
        case .other: return "Other"
        }
    }
}

/// A clip as the history list shows it, without its data.
public struct ClipSummary: Identifiable, Equatable, Sendable {
    public let id: Int64
    public var kind: ClipKind
    public var title: String
    public var sourceBundleID: String?
    public var sourceName: String?
    public var byteSize: Int
    public var created: Date
    public var lastUsed: Date
    public var useCount: Int
    public var pinned: Bool
    public var groupID: Int64?
    public var hasThumbnail: Bool
}

public struct ClipGroup: Identifiable, Equatable, Hashable, Sendable {
    public let id: Int64
    public var name: String
    public var clipCount: Int
}

public enum ClipFilter: Equatable, Hashable, Sendable {
    case all
    case pinned
    case group(Int64)
}

public enum ClipText {
    /// One-line preview: whitespace runs (newlines included) collapse to one space.
    public static func title(_ text: String, limit: Int = 300) -> String {
        var result = ""
        var count = 0
        var pendingSpace = false
        for character in text {
            if character.isWhitespace {
                pendingSpace = !result.isEmpty
                continue
            }
            if count >= limit {
                result.append("…")
                break
            }
            if pendingSpace {
                result.append(" ")
                count += 1
                pendingSpace = false
            }
            result.append(character)
            count += 1
        }
        return result
    }

    /// Normalised text for searching: case-folded (Unicode-aware, so Cyrillic works too).
    public static func searchKey(_ text: String, limit: Int = 100_000) -> String {
        String(text.prefix(limit)).folding(options: [.caseInsensitive, .widthInsensitive], locale: nil)
    }
}
